#!/usr/bin/env python3
"""Turn a logic-analyzer I2C capture into an imx563.c register table.

The IMX563's init sequence is the one part of the driver that can't be
written from public docs. The quickest legal-to-obtain source is the module
itself: Waveshare also sells an IMX563 OIS *USB* camera whose UVC bridge
programs the same sensor over I2C at power-up and on every mode change.
Clip a logic analyzer (Saleae, or any sigrok-supported one) onto its SDA/SCL
test points, capture power-on -> stream, export the I2C decode, and feed it
to this script.

Accepted inputs:
  * Saleae Logic 2 "Export Table" CSV of the I2C analyzer
    (columns: name,type,start_time,duration,ack,address,read,data)
  * sigrok-cli text output, e.g.
      sigrok-cli -i cap.sr -P i2c:scl=D0:sda=D1 \
                 -A i2c=start:repeat-start:stop:address-read:address-write:data-read:data-write
    (add --protocol-decoder-samplenum to get gap/delay detection)

Output: C `struct cci_reg_sequence` rows. Gaps longer than --gap-ms become
comments (they usually mark required delays, e.g. after software reset).
The 0x0100 = 0x01 (stream on) write is called out, since everything before
it in the last block is the mode setup.

Example:
  i2c_log_to_regs.py capture.csv --addr 0x1a > imx563_init.inc
  i2c_log_to_regs.py capture.csv --addr 0x0c --reg-bits 8   # VCM traffic
"""

import argparse
import csv
import re
import sys


class Txn:
    """One I2C transaction: START, address, data bytes, STOP/repeated START."""

    def __init__(self, t, addr, read):
        self.t = t
        self.addr = addr
        self.read = read
        self.data = []


def parse_saleae(path):
    txns, cur = [], None
    with open(path, newline="") as f:
        for row in csv.DictReader(f):
            kind = row.get("type", "").strip('"').lower()
            t = float(row.get("start_time") or 0)
            if kind == "address":
                addr = int(row["address"], 0)
                # Logic 2 exports 7-bit addresses; tolerate 8-bit exports.
                if addr > 0x7f:
                    addr >>= 1
                cur = Txn(t, addr, row.get("read", "").lower() == "true")
                txns.append(cur)
            elif kind == "data" and cur is not None:
                cur.data.append(int(row["data"], 0))
            elif kind == "stop":
                cur = None
    return txns


SIGROK_RE = re.compile(
    r"^(?:(?P<s>\d+)-\d+\s+)?i2c-\d+:\s*(?P<what>[A-Za-z -]+?)(?::\s*(?P<val>[0-9A-Fa-f]+))?\s*$")


def parse_sigrok(path, samplerate):
    txns, cur = [], None
    with open(path) as f:
        for line in f:
            m = SIGROK_RE.match(line.strip())
            if not m:
                continue
            what = m["what"].strip().lower()
            t = int(m["s"]) / samplerate if m["s"] and samplerate else 0.0
            if what in ("address write", "address read"):
                cur = Txn(t, int(m["val"], 16), what == "address read")
                txns.append(cur)
            elif what in ("data write", "data read") and cur is not None:
                cur.data.append(int(m["val"], 16))
            elif what == "stop":
                cur = None
    return txns


def to_rows(txns, addr, reg_bits, gap_s):
    nb = reg_bits // 8
    rows, last_t = [], None
    reads = 0
    for tx in txns:
        if tx.addr != addr:
            continue
        if tx.read:
            reads += 1
            continue
        if len(tx.data) <= nb:
            # Register-address-only write = setup for a read; not config.
            continue
        if last_t is not None and gap_s and tx.t - last_t > gap_s:
            rows.append(("gap", (tx.t - last_t) * 1000.0))
        last_t = tx.t
        reg = int.from_bytes(bytes(tx.data[:nb]), "big")
        # Sony sensors auto-increment: a burst writes consecutive registers.
        for i, v in enumerate(tx.data[nb:]):
            rows.append(("w", reg + i, v))
    return rows, reads


def emit(rows, reg_bits, out):
    w = reg_bits // 4
    macro = "CCI_REG8"
    out.write("/* generated by tools/i2c_log_to_regs.py */\n")
    for r in rows:
        if r[0] == "gap":
            out.write(f"\t/* --- {r[1]:.1f} ms gap (delay needed here?) --- */\n")
            continue
        _, reg, val = r
        note = ""
        if reg_bits == 16 and reg == 0x0100:
            note = "  /* STREAM ON */" if val else "  /* standby */"
        elif reg_bits == 16 and reg == 0x0103:
            note = "  /* software reset */"
        out.write(f"\t{{ {macro}(0x{reg:0{w}x}), 0x{val:02x} }},{note}\n")


def main():
    p = argparse.ArgumentParser(description=__doc__,
                                formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("capture")
    p.add_argument("--addr", type=lambda s: int(s, 0), default=0x1a,
                   help="7-bit device address to extract (default 0x1a)")
    p.add_argument("--reg-bits", type=int, choices=(8, 16), default=16)
    p.add_argument("--format", choices=("auto", "saleae", "sigrok"), default="auto")
    p.add_argument("--samplerate", type=float, default=0,
                   help="sigrok sample rate in Hz (enables gap detection)")
    p.add_argument("--gap-ms", type=float, default=2.0)
    a = p.parse_args()

    fmt = a.format
    if fmt == "auto":
        with open(a.capture) as f:
            head = f.readline()
        fmt = "saleae" if "start_time" in head or head.startswith("name,") else "sigrok"

    txns = (parse_saleae(a.capture) if fmt == "saleae"
            else parse_sigrok(a.capture, a.samplerate))
    rows, reads = to_rows(txns, a.addr, a.reg_bits, a.gap_ms / 1000.0)

    seen = sorted({t.addr for t in txns})
    print(f"/* {fmt}: {len(txns)} transactions, devices seen: "
          f"{', '.join(f'0x{x:02x}' for x in seen)} */", file=sys.stderr)
    n = sum(1 for r in rows if r[0] == "w")
    print(f"/* 0x{a.addr:02x}: {n} register writes, {reads} reads */", file=sys.stderr)
    if not n:
        print("no writes for that address — check --addr against 'devices seen'",
              file=sys.stderr)
        return 1
    emit(rows, a.reg_bits, sys.stdout)
    return 0


if __name__ == "__main__":
    sys.exit(main())
